#!/usr/bin/env node
/**
 * Generate V7__seed_projects_from_config.sql from all js/config*.js files.
 * Run from repo root: node packages/api/scripts/generate-config-seed.mjs
 * Output: packages/api/src/db/migrations/V7__seed_projects_from_config.sql
 *
 * Uses CONFIG.DELIVERABLES from each file; creates one workspace per config file,
 * then inserts projects and milestones (planned_date from DD/MM/YYYY).
 */

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, '..', '..', '..');
const JS_DIR = join(REPO_ROOT, 'js');
const MIGRATIONS_DIR = join(__dirname, '..', 'src', 'db', 'migrations');
const OUTPUT_FILE = join(MIGRATIONS_DIR, 'V7__seed_projects_from_config.sql');
const OUTPUT_V9 = join(MIGRATIONS_DIR, 'V9__backfill_workspace_workflows.sql');

function extractConfig(content) {
  try {
    const win = {};
    const fn = new Function('window', content + '; return typeof CONFIG !== "undefined" ? CONFIG : {};');
    return fn(win);
  } catch (e) {
    return null;
  }
}

function normalizeDate(str) {
  if (!str || typeof str !== 'string') return null;
  const parts = str.trim().split('/').map((p) => p.trim());
  if (parts.length < 3) return null;
  const [d, m, y] = parts;
  const day = d.padStart(2, '0');
  const month = m.padStart(2, '0');
  const year = y.length === 2 ? '20' + y : y;
  return `${day}/${month}/${year}`;
}

function sqlEscape(str) {
  if (str == null) return 'NULL';
  if (typeof str !== 'string') return `'${String(str).replace(/'/g, "''")}'`;
  return `'${str.replace(/'/g, "''")}'`;
}

/** Escape JSON for use inside SQL single-quoted string (for ::jsonb). */
function jsonForSql(obj) {
  const raw = JSON.stringify(obj == null ? [] : obj);
  return raw.replace(/\\/g, '\\\\').replace(/'/g, "''");
}

function configFiles() {
  if (!existsSync(JS_DIR)) return [];
  const files = readdirSync(JS_DIR)
    .filter((f) => f.startsWith('config') && f.endsWith('.js'))
    .sort();
  return files.map((f) => ({ name: f, path: join(JS_DIR, f) }));
}

const CONFIG_FILES = configFiles();
if (CONFIG_FILES.length === 0) {
  console.error('No js/config*.js files found. Run from repo root.');
  process.exit(1);
}

function buildWorkflowFromMilestones(CONFIG) {
  const milestones = Array.isArray(CONFIG?.MILESTONES) ? CONFIG.MILESTONES : [];
  if (milestones.length === 0) return [];
  const workflow = [{ type: 'state', key: 'NS', short: 'NS', title: 'Not Started', description: 'Not yet started' }];
  milestones.forEach((m) => {
    workflow.push({
      type: 'milestone',
      key: m.key,
      short: m.short ?? m.key,
      title: m.title ?? m.key,
      subtitle: m.subtitle ?? '',
    });
    workflow.push({
      type: 'state',
      key: m.key + '_S',
      short: m.short ?? m.key,
      title: m.title ?? m.key,
      description: m.subtitle ?? '',
    });
  });
  return workflow;
}

const configs = [];
for (const { name, path: filePath } of CONFIG_FILES) {
  const content = readFileSync(filePath, 'utf8');
  const CONFIG = extractConfig(content);
  const deliverables = CONFIG?.DELIVERABLES;
  const title = CONFIG?.DASHBOARD_TEXT?.title || CONFIG?.ENTITY_LABELS?.plural || name.replace('.js', '');
  const workflow = Array.isArray(CONFIG?.WORKFLOW) && CONFIG.WORKFLOW.length > 0
    ? CONFIG.WORKFLOW
    : buildWorkflowFromMilestones(CONFIG);
  const timeline = CONFIG?.TIMELINE && typeof CONFIG.TIMELINE === 'object' ? CONFIG.TIMELINE : {};
  const settings = {
    start_month: timeline.START_MONTH ?? timeline.start_month ?? '01/2026',
    end_month: timeline.END_MONTH ?? timeline.end_month ?? '12/2026',
  };
  if (Array.isArray(deliverables) && deliverables.length > 0) {
    configs.push({ sourceFile: name, title, deliverables, workflow, settings });
  }
}

if (configs.length === 0) {
  console.error('No DELIVERABLES found in any config file.');
  process.exit(1);
}

const lines = [];
lines.push('-- Seed projects and milestones from js/config*.js (generated by scripts/generate-config-seed.mjs)');
lines.push('-- Requires: at least one org and one user must exist (e.g. from app sign-up).');
lines.push('-- Creates one workspace per config file; inserts projects and milestones.');
lines.push('');
lines.push("DO $$");
lines.push("DECLARE");
lines.push("  v_org_id   UUID;");
lines.push("  v_user_id  UUID;");
lines.push("  v_ws_id    UUID;");
lines.push("  v_proj_id  UUID;");
lines.push("  v_ord      INT;");
lines.push("  v_mk       TEXT;");
lines.push("  v_dt       TEXT;");
lines.push("  v_pd       DATE;");
lines.push("BEGIN");
lines.push("  SELECT id INTO v_org_id FROM organizations WHERE slug = 'config-seed-org' LIMIT 1;");
lines.push("  IF v_org_id IS NULL THEN");
lines.push("    INSERT INTO organizations (id, name, slug)");
lines.push("    VALUES (uuid_generate_v4(), 'Config Import Org', 'config-seed-org')");
lines.push("    RETURNING id INTO v_org_id;");
lines.push("  END IF;");
lines.push("  SELECT id INTO v_user_id FROM users LIMIT 1;");
lines.push("  IF v_user_id IS NULL THEN");
lines.push("    INSERT INTO users (id, auth0_id, email, display_name)");
lines.push("    VALUES (uuid_generate_v4(), 'seed|config-import', 'config-import@local.dev', 'Config Import')");
lines.push("    RETURNING id INTO v_user_id;");
lines.push("  END IF;");
lines.push('');

for (const { sourceFile, title, deliverables, workflow, settings } of configs) {
  const slug = sourceFile.replace('.js', '').replace(/[^a-z0-9]/gi, '-').toLowerCase();
  const wsName = title.length > 80 ? title.slice(0, 77) + '...' : title;
  const workflowJson = jsonForSql(workflow);
  const settingsJson = jsonForSql(settings);

  lines.push("  SELECT id INTO v_ws_id FROM workspaces WHERE org_id = v_org_id AND slug = " + sqlEscape(slug) + " LIMIT 1;");
  lines.push("  IF v_ws_id IS NULL THEN");
  lines.push("    INSERT INTO workspaces (id, org_id, name, slug, created_by, workflow_definition, settings)");
  lines.push("    VALUES (uuid_generate_v4(), v_org_id, " + sqlEscape(wsName) + ", " + sqlEscape(slug) + ", v_user_id, '" + workflowJson + "'::jsonb, '" + settingsJson + "'::jsonb)");
  lines.push("    RETURNING id INTO v_ws_id;");
  lines.push("  ELSE");
  lines.push("    UPDATE workspaces SET workflow_definition = '" + workflowJson + "'::jsonb, settings = '" + settingsJson + "'::jsonb WHERE id = v_ws_id;");
  lines.push("  END IF;");
  lines.push("  v_ord := 0;");
  lines.push('');

  let displayOrder = 0;
  for (const d of deliverables) {
    const name = d.name || 'Unnamed';
    if (!name) continue;
    displayOrder += 1;
    const groupName = d.group != null ? String(d.group) : null;
    const atRisk = !!d.atRisk;
    const descoped = !!d.descoped;
    const showInTimeline = d.showInTimeline !== false;
    const link = d.link != null ? String(d.link) : null;
    const tags = Array.isArray(d.tags) ? d.tags : [];
    const tagsSql = tags.length ? "ARRAY[" + tags.map((t) => sqlEscape(String(t))).join(',') + "]::TEXT[]" : "'{}'";

    lines.push("  v_ord := " + displayOrder + ";");
    lines.push("  INSERT INTO projects (id, workspace_id, org_id, name, group_name, at_risk, descoped, show_in_timeline, tags, external_link, display_order)");
    lines.push("  VALUES (uuid_generate_v4(), v_ws_id, v_org_id, " + sqlEscape(name) + ", " + sqlEscape(groupName) + ", " + atRisk + ", " + descoped + ", " + showInTimeline + ", " + tagsSql + ", " + sqlEscape(link) + ", v_ord)");
    lines.push("  ON CONFLICT (workspace_id, name) DO NOTHING;");
    lines.push("  SELECT id INTO v_proj_id FROM projects WHERE workspace_id = v_ws_id AND name = " + sqlEscape(name) + " LIMIT 1;");
    lines.push("  IF v_proj_id IS NOT NULL THEN");
    const milestones = d.milestones && typeof d.milestones === 'object' ? d.milestones : {};
    for (const [key, value] of Object.entries(milestones)) {
      const dateStr = normalizeDate(value);
      if (!dateStr) continue;
      lines.push("    v_mk := " + sqlEscape(key) + "; v_dt := " + sqlEscape(dateStr) + "; v_pd := TO_DATE(v_dt, 'DD/MM/YYYY');");
      lines.push("    INSERT INTO milestones (project_id, org_id, milestone_key, planned_date, status)");
      lines.push("    VALUES (v_proj_id, v_org_id, v_mk, v_pd, 'planned')");
      lines.push("    ON CONFLICT (project_id, milestone_key) DO UPDATE SET planned_date = EXCLUDED.planned_date;");
    }
    lines.push("  END IF;");
    lines.push('');
  }
  lines.push('');
}

lines.push("  -- Add all existing users to the seed org so they can see seeded workspaces");
lines.push("  INSERT INTO org_members (org_id, user_id, role)");
lines.push("  SELECT v_org_id, u.id, 'admin' FROM users u");
lines.push("  ON CONFLICT (org_id, user_id) DO NOTHING;");
lines.push('');

lines.push("END $$;");
lines.push('');

writeFileSync(OUTPUT_FILE, lines.join('\n'), 'utf8');
console.log('Wrote ' + OUTPUT_FILE);

const v9Lines = [];
v9Lines.push('-- Backfill workflow_definition and settings for seed workspaces (run after V7 if workspaces already existed).');
v9Lines.push('-- Generated by scripts/generate-config-seed.mjs');
v9Lines.push('');
v9Lines.push("DO $$");
v9Lines.push("DECLARE");
v9Lines.push("  v_org_id UUID;");
v9Lines.push("BEGIN");
v9Lines.push("  SELECT id INTO v_org_id FROM organizations WHERE slug = 'config-seed-org' LIMIT 1;");
v9Lines.push("  IF v_org_id IS NULL THEN RETURN; END IF;");
v9Lines.push('');

for (const { sourceFile, workflow, settings } of configs) {
  const slug = sourceFile.replace('.js', '').replace(/[^a-z0-9]/gi, '-').toLowerCase();
  const workflowJson = jsonForSql(workflow);
  const settingsJson = jsonForSql(settings);
  v9Lines.push("  UPDATE workspaces SET workflow_definition = '" + workflowJson + "'::jsonb, settings = '" + settingsJson + "'::jsonb");
  v9Lines.push("  WHERE org_id = v_org_id AND slug = " + sqlEscape(slug) + ";");
  v9Lines.push('');
}

v9Lines.push("END $$;");
v9Lines.push('');

writeFileSync(OUTPUT_V9, v9Lines.join('\n'), 'utf8');
console.log('Wrote ' + OUTPUT_V9);
console.log('Configs: ' + configs.map((c) => c.sourceFile + ' (' + c.deliverables.length + ' projects)').join(', '));
